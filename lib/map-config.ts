/**
 * Map / history change configuration. These are the JSON shapes queued as
 * `province_history` and `country_history`, and the exact file is always
 * resolved server-side and carried in ChangeItem.targetFile.
 */
export interface ProvinceConfig {
  id: number;
  name?: string;
  name_cn?: string;
  name_en?: string;
  owner?: string;
  controller?: string;
  religion?: string;
  culture?: string;
  base_tax?: number;
  base_production?: number;
  base_manpower?: number;
  trade_goods?: string;
  /** Optional dated key such as "1444.11.11"; omit to edit the start block. */
  date?: string;
  add_core?: string[];
  remove_core?: string[];
  /** Ask the batch prompt to update province-name localisation keys. */
  localisation?: boolean;
}

export interface CountryConfig {
  tag: string;
  name?: string;
  government?: string;
  religion?: string;
  technology_group?: string;
  primary_culture?: string;
  capital?: number;
  add_monarch?: {
    name: string;
    adm: number;
    dip: number;
    mil: number;
    birth_date?: string;
    death_date?: string;
    heir?: boolean;
  };
  /** Ask the batch prompt to update country-name localisation keys. */
  localisation?: boolean;
}

/** Same shape as ProvinceConfig, named for the province-history panel. */
export type ProvinceHistoryConfig = ProvinceConfig;
/** Same shape as CountryConfig, named for the country-history panel. */
export type CountryHistoryConfig = CountryConfig;

/** A brand-new country tag: four files are generated by the batch task. */
export interface NewTagConfig {
  tag: string;
  name: string;
  adjective?: string;
  government: string;
  religion: string;
  technology_group: string;
  primary_culture: string;
  capital?: number;
  /** EU4 color as { r, g, b } (0-255). */
  color?: { r: number; g: number; b: number };
  add_monarch?: CountryConfig['add_monarch'];
  localisation?: boolean;
  /** Reminder shown to the user: the flag file is manual. */
  flag_note?: string;
}

export interface NationalIdeaSlot {
  /** Native EU4 value; the UI converts percentages for display (0.10 -> 10). */
  modifier?: string;
  value?: number;
  /** Full list when a block carries more than one modifier. */
  modifiers?: Array<{ modifier: string; value: number }>;
}

export interface NationalIdea {
  /** English id, e.g. fra_taille. */
  id: string;
  /** Chinese name text written to localisation. */
  name: string;
  /** Chinese description text written to localisation. */
  desc: string;
  modifier?: string;
  value?: number;
  modifiers?: Array<{ modifier: string; value: number }>;
}

export interface NationalIdeasConfig {
  tag: string;
  traditions: NationalIdeaSlot[];
  ambition: NationalIdeaSlot;
  ideas: NationalIdea[];
}

export interface GovernmentReformConfig {
  id: string;
  name: string;
  tier: number;
  potential_government: string;
  modifiers: { modifier: string; value: number }[];
}

export interface TagGovernmentConfig {
  tag: string;
  government_type: string;
  reforms: string[];
}
